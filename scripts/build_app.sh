#!/bin/bash
# Build Loki.app — a double-clickable launcher for the local server.
#
#   scripts/build_app.sh              build into the project folder
#   scripts/build_app.sh --desktop    build, then put a copy on the Desktop
#   scripts/build_app.sh --apps       build, then put a copy in /Applications
#
# The app starts the server if it is not already running, then opens your
# browser. It exits straight away; the server keeps running in the background.
# Stop the server with:  bin/loki stop

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
APP="$ROOT/Loki.app"
SELF_ARGS="$*"   # kept for the retry hint below
PORT="${LOKI_PORT:-8713}"

if [ ! -x "$ROOT/.venv/bin/python" ]; then
    echo "No virtualenv at $ROOT/.venv — run the install steps in README.md first." >&2
    exit 1
fi

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# ----------------------------------------------------------------- launcher
cat > "$APP/Contents/MacOS/Loki" <<LAUNCHER
#!/bin/bash
# Loki launcher. Generated by scripts/build_app.sh — edit that, not this.
ROOT="$ROOT"
PORT="$PORT"
LAUNCHER
cat >> "$APP/Contents/MacOS/Loki" <<'LAUNCHER'
URL="http://127.0.0.1:${PORT}"
LOG="$ROOT/data/logs/app.log"
mkdir -p "$ROOT/data/logs"

# IMPORTANT: this script must finish within a moment.
#
# A bash script has no Cocoa event loop, so if it stays in the foreground
# macOS shows it in the Dock, gets no answer to its Apple Events, and marks it
# "not responding". LaunchServices then tries to re-activate that stuck
# instance instead of launching a new one, and clicking the icon does nothing.
#
# So: start the server detached, hand off the waiting to a background
# subshell, and exit straight away.

{ echo; echo "=== clicked $(date) ==="; } >>"$LOG" 2>&1

note() {
    /usr/bin/osascript -e "display dialog \"$1\" with title \"Loki\" buttons {\"OK\"} default button 1 with icon caution" >/dev/null 2>&1 || true
}

healthy() {
    /usr/bin/curl -fsS -m 2 "${URL}/api/health" >/dev/null 2>&1
}

if [ ! -x "$ROOT/.venv/bin/python" ]; then
    note "Loki cannot find its Python environment at:\n\n$ROOT/.venv\n\nIf you moved the Loki folder, open Terminal and run scripts/build_app.sh --desktop from its new location."
    exit 1
fi

# Already up: just show the page.
if healthy; then
    echo "already running; opening $URL" >>"$LOG" 2>&1
    /usr/bin/open "$URL"
    exit 0
fi

# Start the server, fully detached so it outlives this launcher.
cd "$ROOT"
nohup "$ROOT/.venv/bin/python" -m loki.cli serve --port "$PORT" >>"$LOG" 2>&1 &
disown 2>/dev/null || true

# Wait for it in the background, then open the browser. Detached as well, so
# this script can return to LaunchServices immediately.
nohup bash -c '
    URL="'"$URL"'"
    LOG="'"$LOG"'"
    for _ in $(seq 1 120); do
        if /usr/bin/curl -fsS -m 2 "${URL}/api/health" >/dev/null 2>&1; then
            /usr/bin/open "$URL"
            exit 0
        fi
        sleep 0.5
    done
    /usr/bin/osascript -e "display dialog \"Loki did not start within a minute.\n\nSee the log at:\n${LOG}\" with title \"Loki\" buttons {\"OK\"} default button 1 with icon caution" >/dev/null 2>&1
' >>"$LOG" 2>&1 &
disown 2>/dev/null || true

exit 0
LAUNCHER
chmod +x "$APP/Contents/MacOS/Loki"

# ----------------------------------------------------------------- metadata
cp "$ROOT/assets/loki.icns" "$APP/Contents/Resources/loki.icns"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>                 <string>Loki</string>
    <key>CFBundleDisplayName</key>          <string>Loki</string>
    <key>CFBundleIdentifier</key>           <string>local.loki.app</string>
    <key>CFBundleVersion</key>              <string>1.0</string>
    <key>CFBundleShortVersionString</key>   <string>1.0</string>
    <key>CFBundleExecutable</key>           <string>Loki</string>
    <key>CFBundleIconFile</key>             <string>loki.icns</string>
    <key>CFBundlePackageType</key>          <string>APPL</string>
    <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
    <key>LSMinimumSystemVersion</key>       <string>11.0</string>
    <key>NSHighResolutionCapable</key>      <true/>
    <key>LSApplicationCategoryType</key>    <string>public.app-category.reference</string>
    <!-- The launcher exits immediately, so it must not claim a Dock slot. -->
    <key>LSUIElement</key>                  <true/>
</dict>
</plist>
PLIST

# An ad-hoc signature stops Gatekeeper complaining about a damaged bundle.
/usr/bin/codesign --force --deep --sign - "$APP" >/dev/null 2>&1 || true
/usr/bin/touch "$APP"

echo "Built $APP"

install_copy() {
    local target="$1"

    # macOS protects existing app bundles, and the Desktop folder on top of
    # that. Replacing one from a terminal needs Privacy permissions that are
    # not worth asking for, so say plainly what to do instead.
    if [ -e "$target" ]; then
        if ! rm -rf "$target" 2>/dev/null; then
            echo
            echo "Could not replace $target"
            echo "macOS protects app bundles that already exist there."
            echo
            echo "Drag that one to the Trash in Finder, then run this again:"
            echo "  scripts/build_app.sh $SELF_ARGS"
            echo
            return 1
        fi
    fi

    if ! /bin/cp -R "$APP" "$target" 2>/dev/null; then
        echo "Could not copy the app to $target" >&2
        return 1
    fi
    /usr/bin/touch "$target"
    echo "Installed $target"
}

for arg in "$@"; do
    case "$arg" in
        --desktop) install_copy "$HOME/Desktop/Loki.app" ;;
        --apps)    install_copy "/Applications/Loki.app" ;;
    esac
done

echo
echo "Double-click it to start Loki and open the page."
echo "To stop the server later:  bin/loki stop"
